"""Generate version-specific provider binding. Never copy OpenClaw API keys."""
import argparse
import json
import re
from pathlib import Path

parser = argparse.ArgumentParser()
parser.add_argument('--provider-id', help='Non-secret provider ID for an image build')
args = parser.parse_args()

plugin = Path(__file__).resolve().parents[1]
if args.provider_id:
    if not re.fullmatch(r'[A-Za-z0-9][A-Za-z0-9._-]{0,127}', args.provider_id):
        raise SystemExit('Invalid provider ID')
    pid = args.provider_id
else:
    config = Path.home() / ".openclaw" / "openclaw.json"
    if not config.is_file():
        raise SystemExit(f"OpenClaw config tidak ditemukan: {config}")

    providers = json.loads(config.read_text()).get("models", {}).get("providers", {})
    matches = [(pid, provider) for pid, provider in providers.items()
               if any(model.get("id") == "openclaw" for model in provider.get("models", []))]
    if len(matches) != 1:
        raise SystemExit(f"Harus ada tepat 1 provider model combo 'openclaw'; ditemukan {len(matches)}")
    pid, provider = matches[0]
    if not provider.get("baseUrl"):
        raise SystemExit("Provider custom tidak memiliki baseUrl")

(plugin / "src" / "provider-id.generated.ts").write_text(
    f"// Local deployment binding generated by tools/configure_plugin.py. No secrets.\nexport const PROVIDER_ID = {json.dumps(pid)};\n"
)
manifest = {
    "id": "mandala-9router-video",
    "name": "Mandala 9Router Video Understanding",
    "description": "9Router 0.5.95 MP4 video understanding compatibility transport",
    "version": "0.1.0",
    "contracts": {"mediaUnderstandingProviders": [pid]},
    "mediaUnderstandingProviderMetadata": {
        pid: {"capabilities": ["video"], "defaultModels": {"video": "openclaw"}}
    },
    "configSchema": {"type": "object", "additionalProperties": False, "properties": {}}
}
(plugin / "openclaw.plugin.json").write_text(json.dumps(manifest, indent=2) + "\n")
print("Generated provider binding for:", pid)
print("No API keys written")
